def _source_cage():
    """Reproduce anatomy_core.py's retained cage and original source mapping."""
    path = Path(__file__).resolve().parents[1] / "assets/kevin/anatomical-head.npz"
    with np.load(path) as data:
        vertices = data["vertices"]
        faces = data["faces"]
        faces = faces[np.min(vertices[faces, 2], axis=1) > 1.475]
        used = np.unique(faces)
        remap = np.full(len(vertices), -1, dtype=np.int32)
        remap[used] = np.arange(len(used))
        return remap[faces], data["source_indices"][used].copy()


def _mesh_topology(mesh):
    """A stable ordering check, not merely a vertex-count heuristic."""
    indices = np.empty(len(mesh.loops), dtype=np.int32)
    mesh.loops.foreach_get("vertex_index", indices)
    totals = np.empty(len(mesh.polygons), dtype=np.int32)
    mesh.polygons.foreach_get("loop_total", totals)
    return totals, indices


def add_face_morphs(obj):
    """Add exactly mouthOpen, blink, smile, and frown to the baked head.

    Returns per-key affected-vertex counts and maximum displacement in metres.
    Raises a descriptive ValueError instead of silently attaching expressions
    to the wrong topology. The original mesh and its material/color data are
    otherwise preserved. This function does not change bones or eyeballs.
    """
    if obj.type != "MESH":
        raise TypeError("Kevin facial morphs require a mesh object.")
    if obj.data.shape_keys and any(k.name in _TARGETS for k in obj.data.shape_keys.key_blocks):
        raise ValueError("Kevin facial keys already exist; do not append duplicate expressions.")
    faces, source_ids = _source_cage()
    lookup = {int(source): index for index, source in enumerate(source_ids)}
    cage = bpy.data.meshes.new("__Kevin_expression_transfer_cage")
    cage.from_pydata([(0.0, 0.0, 0.0)] * len(source_ids), [], faces.tolist())
    cage.update()
    transfer = bpy.data.objects.new("__Kevin_expression_transfer", cage)
    bpy.context.scene.collection.objects.link(transfer)
    transfer.hide_render = True
    modifier = transfer.modifiers.new("Source topology interpolation", "SUBSURF")
    modifier.subdivision_type = "CATMULL_CLARK"
    modifier.show_only_control_edges = False
    expected_totals, expected_indices = _mesh_topology(obj.data)
    subdivision = None
    source_to_target = None
    deltas = {}
    try:
        for level in (0, 1, 2):
            modifier.levels = level
            modifier.render_levels = level
            bpy.context.view_layer.update()
            evaluated = transfer.evaluated_get(bpy.context.evaluated_depsgraph_get())
            interpolated = evaluated.to_mesh()
            try:
                if len(interpolated.vertices) != len(obj.data.vertices):
                    continue
                totals, indices = _mesh_topology(interpolated)
                if not np.array_equal(totals, expected_totals):
                    continue
                # Blender can assign generated edge-point indices differently
                # when loading a saved mesh versus constructing from_pydata.
                # Polygon/corner order stays stable, so require a consistent
                # bijective vertex correspondence from all face-loop pairs.
                mapping = np.full(len(obj.data.vertices), -1, dtype=np.int32)
                mapping[indices] = expected_indices
                if (np.array_equal(mapping[indices], expected_indices)
                        and np.array_equal(np.sort(mapping), np.arange(len(mapping)))):
                    source_to_target = mapping
                    subdivision = level
                    break
            finally:
                evaluated.to_mesh_clear()
        if subdivision is None:
            raise ValueError(
                "Head topology does not match Kevin's cage or its Catmull-Clark levels 1/2. "
                "Add facial keys immediately after baking the isolated anatomical head, "
                "before joining, triangulating, or decimating it."
            )
        for name, records in _TARGETS.items():
            displacement = np.zeros((len(source_ids), 3), dtype=np.float32)
            for line in records.splitlines():
                row = line.split()
                if not row:
                    continue
                source = int(row[0])
                x, y, z = map(float, row[1:])
                # MakeHuman source-unit Y-up scale to Kevin's metre Z-up frame.
                displacement[lookup[source]] = (x * .105, -z * .105, y * .105)
            cage.vertices.foreach_set("co", displacement.reshape(-1))
            cage.update()
            bpy.context.view_layer.update()
            evaluated = transfer.evaluated_get(bpy.context.evaluated_depsgraph_get())
            interpolated = evaluated.to_mesh()
            try:
                delta = np.empty((len(obj.data.vertices), 3), dtype=np.float32)
                interpolated.vertices.foreach_get("co", delta.reshape(-1))
                if not np.isfinite(delta).all():
                    raise ValueError("Nonfinite anatomical expression displacement.")
                reordered = np.empty_like(delta)
                reordered[source_to_target] = delta
                deltas[name] = reordered
            finally:
                evaluated.to_mesh_clear()
    finally:
        bpy.data.objects.remove(transfer, do_unlink=True)
        bpy.data.meshes.remove(cage)

    if obj.data.shape_keys is None:
        obj.shape_key_add(name="Basis", from_mix=False)
    basis = obj.data.shape_keys.reference_key
    neutral = np.empty((len(obj.data.vertices), 3), dtype=np.float32)
    basis.data.foreach_get("co", neutral.reshape(-1))
    results = {}
    for name, delta in deltas.items():
        key = obj.shape_key_add(name=name, from_mix=False)
        key.relative_key = basis
        key.slider_min = 0.0
        key.slider_max = 1.0
        key.value = 0.0
        key.data.foreach_set("co", (neutral + delta).reshape(-1))
        magnitudes = np.linalg.norm(delta, axis=1)
        results[name] = {
            "affected_vertices": int(np.count_nonzero(magnitudes > 1e-7)),
            "maximum_displacement_m": float(magnitudes.max()),
        }
    obj.data.update()
    obj["facial_morph_provenance"] = "CC0 MakeHuman source-indexed expressions, topology-preserving subdivision"
    obj["facial_morph_subdivision"] = subdivision
    obj["jaw_morph_usage"] = "Keep jaw bone neutral for mouthOpen; bone and key deformations add."
    return results
