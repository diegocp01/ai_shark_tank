import { assertScriptedServer } from '../offline.js';
await assertScriptedServer();
import { chromium, expect } from '@playwright/test';
import { writeFile } from 'node:fs/promises';
const browser = await chromium.launch({ channel: 'chrome', headless: true, args: ['--use-angle=metal'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1 });
const errors = []; const external = [];
page.on('pageerror', e => { errors.push(e.message); console.log('PAGE ERROR', e.message); });
page.on('console', m => { if (m.type() === 'error') console.log('CONSOLE', m.text().slice(0,500)); });
page.on('request', r => { if (/^https?:/.test(r.url()) && !r.url().startsWith('http://127.0.0.1:5056')) external.push(r.url()); });
try {
await page.addInitScript(() => localStorage.setItem('ai-shark-tank:voice', 'false'));
await page.goto('http://127.0.0.1:5056/?quality=high&pitch=odd-sox');
await page.waitForFunction(() => document.querySelector('#stage').dataset.wesModel === 'mark', null, { timeout: 120000 });
await page.screenshot({ path: 'review/realistic-studio/lobby.png' });
await page.getByRole('button', { name: 'Test', exact: true }).click();
await page.keyboard.press('Space');
await page.keyboard.press('ArrowRight');
await page.keyboard.press('ArrowRight');
await page.keyboard.press('ArrowRight');
await page.mouse.move(1400, 20);
await page.locator('body').click({ position: { x: 1400, y: 20 } });
await expect(page.locator('#transport')).toHaveCSS('opacity', '0', { timeout: 6000 });
await page.screenshot({ path: 'review/realistic-studio/pitch.png' });
const shot = await page.locator('#stage').getAttribute('data-shot');
await page.setViewportSize({ width: 390, height: 844 });
await page.goto('http://127.0.0.1:5056/?quality=low&pitch=odd-sox&autoplay=1&speed=40');
await expect(page.locator('#stage')).toHaveAttribute('data-quality', 'low');
await expect(page.locator('body')).toHaveAttribute('data-view', 'show');
await page.keyboard.press('Space');
await page.keyboard.press('ArrowRight');
await page.keyboard.press('ArrowRight');
await page.keyboard.press('ArrowRight');
await page.locator('body').click({ position: { x: 380, y: 20 } });
await expect(page.locator('#transport')).toHaveCSS('opacity', '0', { timeout: 6000 });
await expect(page.locator('#caption')).toBeHidden();
expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
await page.screenshot({ path: 'review/realistic-studio/mobile.png' });
expect(errors).toEqual([]); expect(external).toEqual([]);
const report = { errors, external, shot, desktop: '1440x900, high quality', mobile: '390x844, low quality', idleHUD: 'hidden' };
await writeFile('review/realistic-studio/capture.json', JSON.stringify(report, null, 2) + '\n');
console.log(JSON.stringify(report, null, 2));
} finally { await browser.close(); }
